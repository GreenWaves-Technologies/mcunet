import os
import argparse
import argcomplete
from PIL import Image
from tqdm import tqdm
import numpy as np
import pickle

from nntool.api import NNGraph
from nntool.api.utils import quantization_options, model_settings

CACHED_STATS = "/tmp/mcunet_stats.pickle"

def create_model_parser():
    # create the top-level parser
    parser = argparse.ArgumentParser(prog='nntool_script')

    # Model options
    parser.add_argument('--trained_model', required=True,
                        help="Path to the trained tflite/onnx")
    parser.add_argument('--quant_type', default="ne16", choices=["sq8", "ne16"],
                        help="Quantization options")
    parser.add_argument('--quant_dataset_path', default=None,
                        help="Path to the quantization dataset path")
    parser.add_argument('--load_quantization', action="store_true",
                        help="If the model is already tflite quantized, load quantization, otherwise, use the quant_dataset_path")
    
    # At options
    parser.add_argument('--tensors_dir', default="tensors",
                        help="Where nntool stores the weights/bias tensors dir (only used in generate and performance mode)")
    parser.add_argument('--at_model_path', default="nn_model.c",
                        help="Path to the C autotiler model file to generate (only used in generate mode)")
    parser.add_argument('--expressions_file_path', default="nn_expressions.c",
                        help="Path to the C file generated by nntool for the expressions kernels")
    parser.add_argument('--flash_type', default="flash", choices=["flash", "mram"],
                        help="Flash type")
    parser.add_argument('--trace_exec', action="store_true", help="Useful in debug to track execution")

    # Test image
    parser.add_argument('--test_image', default=None, help="Path to image to test")
    return parser

def representative_dataset(q_dataset_path):
    for file in tqdm(os.listdir(q_dataset_path)):
        filepath = os.path.join(q_dataset_path, file)
        img = (np.array(Image.open(filepath).resize((160, 160))).astype(np.float32) / 255 - 0.5) / 0.5
        # transpose to CHW
        yield img.transpose((2, 0, 1))

def read_cached_stats():
    if os.path.exists(CACHED_STATS):
        print(f"Loading stats from {str(CACHED_STATS)}")
        with open(str(CACHED_STATS), "rb") as f:
            return pickle.load(f)
    return None

def build_nntool_graph(trained_model, quant_type, load_quantization, quant_dataset_path) -> NNGraph:
    print(f"Building model with {quant_type} Quantization options")
    
    print(trained_model)
    
    G = NNGraph.load_graph(
        trained_model,
        load_quantization=load_quantization,
        old_dsp_lib=False
    )
    G.adjust_order()
    G.fusions('scaled_match_group')
    if not load_quantization:
        stats = read_cached_stats()
        if stats is None:
            print("No cached stats found, rerunning calibration")
            stats = G.collect_statistics(representative_dataset(quant_dataset_path))
            with open(CACHED_STATS, "wb") as f:
                pickle.dump(stats, f)
    else:
        stats = None

    G.quantize(
        stats,
        graph_options=quantization_options(
            use_ne16="ne16" in quant_type,
            hwc=True
        ),
    )

    print(G.qshow([G[0]]))
    print(G.qshow([G[-1]]))
    print(G.show([G[0]]))
    print(G.show([G[-1]]))
    return G

if __name__ == "__main__":
    
    parser = create_model_parser()
    argcomplete.autocomplete(parser)
    args = parser.parse_args()

    G = build_nntool_graph(
        args.trained_model,
        args.quant_type,
        args.load_quantization,
        args.quant_dataset_path
    )
    G.name = "MCUNet"
    if args.test_image:
        img = (np.array(Image.open(args.test_image).resize((160, 160))).astype(np.float32) / 255 - 0.5) / 0.5
        nntool_out = G.execute([img], dequantize=False, quantize=True)
        print(f"NNTool predicted class on {args.test_image}: {np.argmax(nntool_out[-1][0]) + 1} with confidence {np.max(nntool_out[-1][0])}")


    G[0].at_options.allocate = 1
    expressions_file_name = os.path.splitext(os.path.split(args.expressions_file_path)[-1])[0]
    G.gen_at_model(
        write_constants=True,
        directory=os.path.split(args.at_model_path)[0],
        settings=model_settings(
            tensor_directory=args.tensors_dir,
            model_directory=os.path.split(args.at_model_path)[0],
            model_file=os.path.split(args.at_model_path)[1],
            l3_ram_device="AT_MEM_L3_DEFAULTRAM",
            l3_flash_device="AT_MEM_L3_DEFAULTFLASH" if args.flash_type == "flash" else "AT_MEM_L3_MRAMFLASH",
            graph_l1_promotion=2,
            graph_size_opt=2,
            graph_const_exec_from_flash=True,
            graph_async_fork=True,
            graph_trace_exec=args.trace_exec,
            # privileged_l3_flash_device="AT_MEM_L3_MRAMFLASH",
            # privileged_l3_flash_size=int(1.8*1024*1024),
            basic_kernel_header_file=f"{expressions_file_name}.h",
            basic_kernel_source_file=f"{expressions_file_name}.c",
        )
    )
